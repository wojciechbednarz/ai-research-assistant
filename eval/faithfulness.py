import logging

from httpx import AsyncClient
from pydantic import TypeAdapter, ValidationError

from api import send_post_request
from config import get_settings

from .load_golden import ExpectedClaim

settings = get_settings()
logger = logging.getLogger(__name__)


class NoClaimsException(Exception):
    pass


class ModelReturnedNoText(Exception):
    pass


FAITHFULNESS_SYSTEM_PROMPT = """
You are a faithfulness judge for a RAG system.

You receive a CONTEXT (retrieved documents) and an ANSWER (generated by another model).
Your job: check whether every claim in the ANSWER is supported by the CONTEXT.

Step 1 — split the ANSWER into claims:
- One fact per claim.
- Split sentences that join two facts with "and" — but NOT ranges or pairs that form one fact
  (e.g. "between -1 and 1" stays together).
- Replace "it", "this", "they" with what they refer to, so each claim stands alone.
- Skip statements that are not facts (e.g. "I cannot answer your question").

Step 2 — mark each claim:
- "S" (supported): the CONTEXT states it or directly implies it — you could prove the claim
  true using only the CONTEXT.
- "U" (unsupported): the CONTEXT contradicts it or never mentions it.
- Shared words are not enough. Use only the CONTEXT, never your own knowledge.
- The CONTEXT may be in another language (e.g. Polish); judge the meaning, not the language.

Return ONLY a JSON array, no prose, no markdown fences:
[{"claim": "<claim text>", "mark": "S"}, {"claim": "<claim text>", "mark": "U"}]
"""

FAITHFULNESS_USER_PROMPT = """
CONTEXT:
{context}

ANSWER:
{answer}
"""


async def score_faithfulness(row, client: AsyncClient) -> float | None:
    messages = [
        {"role": "system", "content": FAITHFULNESS_SYSTEM_PROMPT},
        {
            "role": "user",
            "content": FAITHFULNESS_USER_PROMPT.format(
                context="\n\n".join(item.document for item in row.retrieved_context),
                answer=row.generated_answer,
            ),
        },
    ]
    payload = {
        "model": settings.OPENROUTER_LLM_DEFAULT_MODEL,
        "messages": messages,
        "temperature": 0,
        "max_tokens": get_settings().LLM_MAX_TOKENS,
    }
    response = await send_post_request(
        client=client, url=get_settings().CHAT_COMPLETIONS_URL, payload=payload
    )
    content = response["choices"][0]["message"]["content"]
    try:
        if content is None:
            raise ModelReturnedNoText("No text returned by the LLM")
        content = content.strip()
        if content.startswith("```"):
            lines = content.splitlines()
            content = "\n".join(lines[1:-1])
        claims = TypeAdapter(list[ExpectedClaim]).validate_json(content)
        if not claims:
            raise NoClaimsException("Could not find any claim in the content.")
        supported_count = len([item.mark for item in claims if item.mark == "S"])
        total = len(claims)
        faithfulness_score = supported_count / total
        return faithfulness_score

    except ValidationError as exc:
        logger.error("Judge reply is not a valid claim list: %s. Error: %s", content, exc)
        raise
